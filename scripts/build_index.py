# -*- coding: utf-8 -*-
"""Build the multi-group summary (index) page for group daily reports.

Usage:
    python build_index.py <spec.json> <output.html>

spec.json structure:
{
  "report_date": "2026-10-21",
  "range_label": "各群统计范围不完全一致，见卡片内标注",   // optional
  "groups": [
    {
      "name": "马吉私域群",
      "file": "马吉私域群日报_2026-10-21.html",
      "range_label": "2026-10-21 00:00 ～ 2026-10-22 00:41",
      "total": "279", "members": "65",
      "peak": "19:00", "top_speaker": "老马 · 48条",
      "highlights": ["老马晚间大分享", "吉吉日谈003", "吉吉当选组长"]
    }
  ]
}
"""
import json
import sys
import html
import datetime

from report_style import CSS

WEEKDAYS_CN = ["周一", "周二", "周三", "周四", "周五", "周六", "周日"]


def esc(text):
    return html.escape(str(text), quote=True)


def build_group_card(group):
    """Render one clickable group card on the summary page."""
    highlights = group.get("highlights", [])[:3]
    hl_html = "".join(
        '<div class="gc-hl">%s</div>' % esc(t) for t in highlights
    )
    hl_title = '<div class="gc-hl-title">今日看点</div>' if highlights else ""
    return """
    <a class="group-card" href="%(file)s">
      <div class="gc-name">%(name)s</div>
      <div class="gc-range">%(range)s</div>
      <div class="gc-stats">
        <div class="gc-stat"><b>%(total)s</b><span>消息</span></div>
        <div class="gc-stat"><b>%(members)s</b><span>发言人数</span></div>
        <div class="gc-stat"><b>%(peak)s</b><span>高峰时段</span></div>
      </div>
      <div class="gc-hl-title">活跃之星 · %(top)s</div>
      %(hl_title)s
      %(highlights)s
      <div class="gc-open">查看完整日报 →</div>
    </a>""" % {
        "file": esc(group.get("file", "#")),
        "name": esc(group.get("name", "")),
        "range": esc(group.get("range_label", "")),
        "total": esc(group.get("total", "")),
        "members": esc(group.get("members", "")),
        "peak": esc(group.get("peak", "")),
        "top": esc(group.get("top_speaker", "")),
        "hl_title": hl_title,
        "highlights": hl_html,
    }


def build_page(spec):
    report_date = spec["report_date"]
    dt = datetime.date.fromisoformat(report_date)
    weekday = WEEKDAYS_CN[dt.weekday()]
    date_cn = "%s年%d月%d日（%s）" % (dt.year, dt.month, dt.day, weekday)
    cards = "\n".join(build_group_card(g) for g in spec["groups"])
    range_line = ""
    if spec.get("range_label"):
        range_line = '<div class="sub">%(range)s</div>' % {"range": esc(spec["range_label"])}

    return """<!DOCTYPE html>
<html lang="zh-CN">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>群聊日报汇总 · %(date)s</title>
<style>%(css)s</style>
</head>
<body>
<div class="wrap">

  <header>
    <span class="tag">群聊日报 · DAILY SUMMARY</span>
    <h1>群聊日报汇总</h1>
    <div class="sub">%(date_cn)s · 共 %(n)d 个群</div>
    %(range_line)s
  </header>

  <div class="group-grid">
%(cards)s
  </div>

  <footer>群聊日报汇总 · 由 Claude 自动生成 · %(today)s · Generated by <a href="https://github.com/duxingzhe1979/wechat-group-daily-report" style="text-decoration:none;border-bottom:1px dotted #999">笃行者AI</a></footer>
</div>
</body>
</html>
""" % {
        "date": report_date,
        "date_cn": date_cn,
        "n": len(spec["groups"]),
        "range_line": range_line,
        "css": CSS,
        "cards": cards,
        "today": datetime.date.today().isoformat(),
    }


def main():
    if len(sys.argv) != 3:
        print("Usage: python build_index.py <spec.json> <output.html>")
        sys.exit(1)
    with open(sys.argv[1], "r", encoding="utf-8") as f:
        spec = json.load(f)
    page = build_page(spec)
    with open(sys.argv[2], "w", encoding="utf-8") as f:
        f.write(page)
    print("Index written to: %s" % sys.argv[2])


if __name__ == "__main__":
    main()
